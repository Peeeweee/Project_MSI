import type { SectionId } from './sections';

export type VertebrateId =
  | 'human'
  | 'shark'
  | 'teleost'
  | 'frog'
  | 'crocodile'
  | 'parrot'
  | 'dog'
  | 'horse';

export interface AnatomicalSubPart {
  readonly id: string;
  readonly tag: 'A' | 'B' | 'C' | 'D';
  readonly label: string;
  readonly origin: string;
  readonly description: string;
  /** Live bone name inside rigged animal GLB (omitted for morph-target bird or human meshes) */
  readonly boneName?: string;
  /** Exact 3D mesh id in muscles.glb for Human model click-isolation */
  readonly muscleId?: string;
  /** 3D local offset from tracked bone (or relative to model center for non-boned models) */
  readonly offset: readonly [number, number, number];
  /** Screen-space leader offset [dx, dy] in px so nearby labels fan out cleanly without overlapping */
  readonly calloutShift: readonly [number, number];
}

export interface VertebrateCallout {
  readonly sectionId: SectionId;
  readonly title: string;
  readonly structure: string;
  readonly note: string;
  /** Bone name inside the rigged GLB to track in real time (falls back to offset) */
  readonly boneName?: string;
  /** Local offset in normalized model coordinates */
  readonly offset: readonly [number, number, number];
  /** Curated camera yaw (deg), elevation & distance when focusing this section */
  readonly focusYawDeg: number;
  readonly focusPitchY: number;
  readonly focusDist: number;
  /** Precise, animal-specific anatomical sub-part labels revealed when this section is clicked */
  readonly parts: readonly AnatomicalSubPart[];
}

export interface VertebrateSpecimen {
  readonly id: VertebrateId;
  readonly label: string;
  readonly clade: string;
  readonly subtitle: string;
  readonly modelUrl: string;
  readonly attribution: string;
  readonly targetSize: number;
  readonly hoverHeight: number;
  /** Optional Y-axis rotation (radians) so all animals face +Z consistently */
  readonly modelRotationY?: number;
  readonly defaultAnimation?: string;
  readonly animations: readonly { clip: string; label: string }[];
  readonly defaultYawDeg: number;
  readonly defaultDist: number;
  readonly callouts: Readonly<Record<SectionId, VertebrateCallout>>;
}

